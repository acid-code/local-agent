/**
 * Collects every t('...') key in web/src (plus server strings shown through tMaybe: gallery names, server errors)
 * and writes web/src/i18n/en.ts. Prints keys he.ts is missing. Usage: node scripts/i18n-keys.mjs [--missing-json file]
 */
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const WEB = path.resolve(import.meta.dirname, '..', 'packages/web/src');
export function collectKeys() {
  const keys = new Set();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) { if (entry.name !== 'i18n') walk(full); continue; }
      if (!/\.tsx?$/.test(entry.name)) continue;
      const sf = ts.createSourceFile(full, fs.readFileSync(full, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
      const visit = (node) => {
        if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && ['t', 'tr'].includes(node.expression.text) && node.arguments[0] && (ts.isStringLiteral(node.arguments[0]) || ts.isNoSubstitutionTemplateLiteral(node.arguments[0]))) keys.add(node.arguments[0].text);
        ts.forEachChild(node, visit);
      };
      visit(sf);
    }
  };
  walk(WEB);
  const extra = path.join(WEB, 'i18n', 'extra-keys.json');
  if (fs.existsSync(extra)) for (const key of JSON.parse(fs.readFileSync(extra, 'utf8'))) keys.add(key);
  return [...keys].sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const keys = collectKeys();
  const body = keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(key)},`).join('\n');
  fs.writeFileSync(path.join(WEB, 'i18n', 'en.ts'), `// Generated by scripts/i18n-keys.mjs from the t('...') calls. English text is the key.\nexport const en: Record<string, string> = {\n${body}\n};\n`);
  const heSrc = fs.readFileSync(path.join(WEB, 'i18n', 'he.ts'), 'utf8');
  const he = new Set([...heSrc.matchAll(/^\s+("(?:[^"\\]|\\.)*"):/gm)].map((m) => JSON.parse(m[1])));
  const missing = keys.filter((key) => !he.has(key));
  const out = process.argv.indexOf('--missing-json');
  if (out > 0) fs.writeFileSync(process.argv[out + 1], JSON.stringify(missing, null, 0));
  console.log(`${keys.length} keys, ${missing.length} missing in he.ts`);
}
